import { NavLink, useNavigate } from 'react-router-dom';
import { useState } from 'react';

const SIDEBAR_ITEMS = [
  { to: '/', label: 'Home', icon: HomeIcon, end: true },
  { to: '/library', label: 'Library', icon: LibraryIcon },
  { to: '/for-you', label: 'Community', icon: CommunityIcon },
  { to: '/profile', label: 'Profile', icon: ProfileIcon },
];

export default function Sidebar() {
  const navigate = useNavigate();
  const [syncing, setSyncing] = useState(false);

  const handleSync = () => {
    setSyncing(true);
    setTimeout(() => {
      setSyncing(false);
      navigate('/for-you');
    }, 1200);
  };

  return (
    <aside className="fixed left-0 top-16 bottom-0 w-16 lg:w-20 z-40 glass-panel border-r border-white/5 rounded-none flex flex-col items-center py-6 gap-2">
      {SIDEBAR_ITEMS.map(({ to, label, icon: Icon, end }) => (
        <NavLink
          key={to}
          to={to}
          end={end}
          title={label}
          className={({ isActive }) =>
            `relative w-11 h-11 lg:w-12 lg:h-12 flex items-center justify-center rounded-xl transition-all duration-300 group ${
              isActive
                ? 'bg-neon-cyan/10 text-neon-cyan shadow-neon-cyan border border-neon-cyan/40'
                : 'text-white/40 hover:text-white hover:bg-white/5 border border-transparent'
            }`
          }
        >
          {({ isActive }) => (
            <>
              {isActive && (
                <span className="absolute left-0 top-1/2 -translate-y-1/2 w-0.5 h-6 bg-neon-cyan rounded-r shadow-neon-cyan" />
              )}
              <Icon />
            </>
          )}
        </NavLink>
      ))}

      <div className="flex-1" />

      <NavLink
        to="/settings"
        title="Settings"
        className={({ isActive }) =>
          `w-11 h-11 lg:w-12 lg:h-12 flex items-center justify-center rounded-xl transition-all ${
            isActive ? 'text-neon-purple' : 'text-white/30 hover:text-white/60'
          }`
        }
      >
        <SettingsIcon />
      </NavLink>

      <button
        type="button"
        onClick={handleSync}
        title="AI Sync"
        className="flex flex-col items-center gap-1 text-white/30 hover:text-neon-green transition-colors group"
      >
        <div
          className={`w-11 h-11 lg:w-12 lg:h-12 flex items-center justify-center rounded-xl border border-white/10 group-hover:border-neon-green/50 group-hover:shadow-neon-green transition-all ${
            syncing ? 'animate-spin border-neon-green/60' : ''
          }`}
        >
          <SyncIcon />
        </div>
        <span className="text-[9px] uppercase tracking-wider font-bold hidden lg:block">
          {syncing ? 'Syncing' : 'AI Sync'}
        </span>
      </button>
    </aside>
  );
}

